package inputarchive

import (
	"bytes"
	"compress/gzip"
	"io"
	"math/rand"
	"testing"
)

func TestExpandingEncodingFallsBackToBoundedStoredGzip(t *testing.T) {
	for _, size := range []int{1, 16, 127, 65535, 65536, 1 << 20, MaxSegmentBytes} {
		raw := make([]byte, size)
		_, _ = rand.New(rand.NewSource(11)).Read(raw)
		// Force the expansion branch without depending on a specific flate
		// encoder's choice of Huffman tables or compression version.
		encoded, err := boundSegmentEncoding(raw, make([]byte, newSegmentStoredLimit(size)+1))
		if err != nil || len(encoded) > newSegmentStoredLimit(size) {
			t.Fatalf("stored encoding exceeds the explicit size bound at %d: %v", size, err)
		}
		r, err := gzip.NewReader(bytes.NewReader(encoded))
		if err != nil {
			t.Fatal(err)
		}
		decoded, err := io.ReadAll(r)
		closeErr := r.Close()
		if err != nil || closeErr != nil || !bytes.Equal(decoded, raw) {
			t.Fatalf("stored gzip changed original bytes at %d: %v/%v", size, err, closeErr)
		}
	}
}

func TestCopyBoundsNewObjectsAndReusesExistingEncoding(t *testing.T) {
	const size = 2*(1<<20) + 17
	raw := make([]byte, size)
	_, _ = rand.New(rand.NewSource(29)).Read(raw)
	plan := Manifest{Format: Format, Digest: sum(raw), RawBytes: size, SegmentBytes: 1 << 20, Prefix: "archive/bounded-encoding"}
	objects := &memoryObjects{}
	got, err := Copy(t.Context(), objects, bytes.NewReader(raw), plan, func(Segment) error { return nil })
	if err != nil {
		t.Fatal(err)
	}
	for _, s := range got.Segments {
		if s.StoredBytes > newSegmentStoredLimit(s.RawBytes) {
			t.Fatal("copy emitted an object above its new-encoding bound")
		}
	}
	// Resume must use receipt bytes, including a different valid compressor
	// encoding, rather than requiring a newly generated byte-identical member.
	first := got.Segments[0]
	var old bytes.Buffer
	w, _ := gzip.NewWriterLevel(&old, gzip.NoCompression)
	_, _ = w.Write(raw[:first.RawBytes])
	_ = w.Close()
	first.StoredBytes, first.StoredHash = old.Len(), sum(old.Bytes())
	first.Key = segmentKey(plan.Prefix, 0, first.StoredHash)
	objects.values[first.Key] = old.Bytes()
	plan.Segments = []Segment{first}
	resumed, err := Copy(t.Context(), objects, bytes.NewReader(raw), plan, func(Segment) error { return nil })
	if err != nil || resumed.Segments[0] != first {
		t.Fatal("resume failed to retain the original stored representation", err)
	}
}
