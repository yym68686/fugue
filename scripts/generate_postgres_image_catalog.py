#!/usr/bin/env python3
"""Generate the Go receipt mirror from the canonical CNPG release declaration."""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "deploy/environments/production/cnpg-controller/release.json"
TARGET = ROOT / "internal/pgimage/catalog_receipt_gen.go"


def render(raw: str) -> str:
    # Parse before emitting source, and quote as one string: receipt contents
    # cannot inject Go code. The original bytes remain the source of truth.
    json.loads(raw)
    quoted = json.dumps(raw, ensure_ascii=False)
    return (
        "// Code generated by scripts/generate_postgres_image_catalog.py; DO NOT EDIT.\n"
        "package pgimage\n\n"
        "//go:generate python3 ../../scripts/generate_postgres_image_catalog.py\n"
        f"var approvedRelease = []byte({quoted})\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render(SOURCE.read_text(encoding="utf-8"))
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != generated:
            raise SystemExit("PostgreSQL image receipt drift: run python3 scripts/generate_postgres_image_catalog.py")
    else:
        TARGET.write_text(generated, encoding="utf-8")


if __name__ == "__main__":
    main()
